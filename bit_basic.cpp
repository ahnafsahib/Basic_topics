#include <bits/stdc++.h>
using namespace std;

#define int long long

int main() {
    ios::sync_with_stdio(false);
    cin.tie(nullptr);

    int n = 13; // Binary: 1101


    // =========================================================
    // 1. CHECK i-th BIT
    // =========================================================

    // (n >> i) & 1
    // i-th bit 1 নাকি 0 check করে

    int i = 2;

    if((n >> i) & 1)
        cout << "Bit is 1\n";
    else
        cout << "Bit is 0\n";

    // Example:
    // n = 13 = 1101
    // i = 0 -> 1
    // i = 1 -> 0
    // i = 2 -> 1
    // i = 3 -> 1


    // =========================================================
    // 2. SET i-th BIT
    // =========================================================

    // i-th bit কে 1 করে
    // n = n | (1LL << i)

    n = 13;
    i = 1;

    n = n | (1LL << i);

    // 1101
    // 0010
    // ----
    // 1111 = 15


    // =========================================================
    // 3. CLEAR i-th BIT
    // =========================================================

    // i-th bit কে 0 করে
    // n = n & ~(1LL << i)

    n = 15;
    i = 1;

    n = n & ~(1LL << i);

    // 1111
    // 1101
    // ----
    // 1101 = 13


    // =========================================================
    // 4. TOGGLE i-th BIT
    // =========================================================

    // i-th bit:
    // 0 হলে 1
    // 1 হলে 0

    // XOR (^)

    n = 13;
    i = 1;

    n = n ^ (1LL << i);

    // 1101
    // 0010
    // ----
    // 1111 = 15


    // =========================================================
    // 5. LEFT SHIFT
    // =========================================================

    // n << i
    // সাধারণভাবে n * 2^i

    cout << (5LL << 2) << '\n';

    // 5 = 0101
    // 5 << 2 = 10100 = 20


    // =========================================================
    // 6. RIGHT SHIFT
    // =========================================================

    // n >> i
    // Positive number-এর ক্ষেত্রে n / 2^i

    cout << (20LL >> 2) << '\n';

    // 20 / 4 = 5


    // =========================================================
    // 7. ODD / EVEN
    // =========================================================

    // Last bit 1 -> Odd
    // Last bit 0 -> Even

    n = 13;

    if(n & 1)
        cout << "Odd\n";
    else
        cout << "Even\n";


    // =========================================================
    // 8. REMOVE LOWEST SET BIT
    // =========================================================

    // n & (n - 1)
    //
    // Binary-এর সবচেয়ে ডান পাশের 1 bit remove করে

    n = 12; // 1100

    n = n & (n - 1);

    // 1100
    // 1011
    // ----
    // 1000 = 8


    // =========================================================
    // 9. CHECK POWER OF 2
    // =========================================================

    // Positive n যদি power of 2 হয়:
    //
    // n & (n - 1) == 0

    n = 16;

    if(n > 0 && (n & (n - 1)) == 0)
        cout << "Power of 2\n";


    // =========================================================
    // 10. COUNT SET BITS
    // =========================================================

    // Binary-তে কয়টা 1 আছে

    n = 13; // 1101

    cout << __builtin_popcountll(n) << '\n';

    // Answer = 3


    // =========================================================
    // 11. LOWEST SET BIT
    // =========================================================

    // n & (-n)
    //
    // সবচেয়ে ডান পাশের 1 bit-এর value দেয়

    n = 12; // 1100

    int low = n & (-n);

    cout << low << '\n';

    // Answer = 4
    // 1100
    // 0100 -> lowest set bit


    // =========================================================
    // 12. TRAILING ZERO
    // =========================================================

    // ডান দিক থেকে কয়টা 0 আছে

    n = 40; // 101000

    cout << __builtin_ctzll(n) << '\n';

    // Answer = 3


    // =========================================================
    // 13. LEADING ZERO
    // =========================================================

    // 64-bit representation-এর বাম দিক থেকে
    // কয়টা 0 আছে

    n = 13;

    cout << __builtin_clzll(n) << '\n';


    // =========================================================
    // 14. XOR BASIC PROPERTIES
    // =========================================================

    // x ^ x = 0
    // x ^ 0 = x
    // x ^ y = y ^ x

    cout << (5 ^ 5) << '\n'; // 0
    cout << (5 ^ 0) << '\n'; // 5


    // =========================================================
    // 15. NUMBER -> 64 BIT VECTOR
    // =========================================================

    n = 13;

    vector<int> bits(64);

    for(int i = 0; i < 64; i++)
        bits[i] = (n >> i) & 1;

    // Print MSB -> LSB

    for(int i = 63; i >= 0; i--)
        cout << bits[i];

    cout << '\n';


    // =========================================================
    // 16. 64 BIT VECTOR -> NUMBER
    // =========================================================

    int x = 0;

    for(int i = 0; i < 64; i++) {

        if(bits[i] == 1)
            x += (1LL << i);
    }

    cout << x << '\n';

    return 0;
}
